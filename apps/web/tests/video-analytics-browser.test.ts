import { businessDay } from '../server/video-operations/policy';

const origin = 'http://localhost:3022';
const output = process.env.VIDEO_ANALYTICS_EVIDENCE_DIR ?? resolve(process.cwd(), '../../output/video-analytics-qa');
let userId = '', workspaceId = '', browser: Browser | undefined, context: BrowserContext | undefined;
const runtimeErrors: string[] = [], checks: string[] = [];
beforeAll(async () => {
  if (process.env.ENVIRONMENT_ID !== 'LOCAL_REVIEW' || new URL(process.env.DATABASE_URL!).port !== '55438') throw Error('ISOLATED_REVIEW_REQUIRED');
  await mkdir(output, { recursive: true });
  const email = `video-browser-${randomUUID()}@example.test`, password = `disposable-${randomUUID()}`;
  const result = await auth.api.signUpEmail({ body: { name: '临时数据中台验收', email, password } });
  userId = result.user.id;
  workspaceId = (await db.workspace.create({ data: { name: '临时验收工作空间', slug: `video-browser-${randomUUID()}`, members: { create: { userId, role: 'OWNER' } } } })).id;
  const account = await db.videoAccount.create({ data: { workspaceId, handle: '真实验收账号', externalId: randomUUID() } });
  await db.videoDailyMetric.create({ data: { workspaceId, accountId: account.id, day: new Date(businessDay() + 'T00:00:00Z'), plays: 1234, likes: 40, comments: 5, saves: 10, shares: 3, netFollowers: -2, negativeComments: 0, observedAt: new Date(), source: 'MANUAL', updatedById: userId } });
  const response = await auth.api.signInEmail({ body: { email, password }, asResponse: true });
  expect(response.ok).toBe(true);
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin });
  await context.addCookies(response.headers.getSetCookie().map(value => { const pair = value.split(';')[0]!, split = pair.indexOf('='); return { name: pair.slice(0, split), value: pair.slice(split + 1), url: origin }; }));
}, 90_000);

afterAll(async () => {
  await context?.close(); await browser?.close();
  if (workspaceId) {
    await db.videoDailyMetric.deleteMany({ where: { workspaceId } });
    await db.videoAccount.deleteMany({ where: { workspaceId } });
    await db.workspace.deleteMany({ where: { id: workspaceId } });
  }
  if (userId) await db.user.deleteMany({ where: { id: userId } });
  await writeFile(resolve(output, '数据中台浏览器验收.json'), JSON.stringify({ checks, runtimeErrors, fixtureCleanupVerified: userId ? await db.user.count({ where: { id: userId } }) === 0 : true, usesRealUserPassword: false, paidModelCalls: 0 }, null, 2));
  await db.$disconnect();
}, 30_000);

