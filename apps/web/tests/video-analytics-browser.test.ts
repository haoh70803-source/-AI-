it('supports narrow screens and simulated updates without silent real-data fallback', async () => {
  const page = await context!.newPage(); page.setDefaultTimeout(20000);
  page.on('pageerror', e => runtimeErrors.push(e.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/short-video?demo=1', { waitUntil: 'load', timeout: 60000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const before = await page.locator('.va-metrics strong').first().textContent();
  await page.getByRole('button', { name: '模拟更新', exact: true }).click();
  expect(await page.locator('.va-metrics strong').first().textContent()).not.toBe(before);
  await page.screenshot({ path: resolve(output, '数据中台-移动布局.png'), fullPage: true });
  await page.route('**/api/video-data?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: '验收用同步失败' }) }));
  await page.getByRole('button', { name: '返回真实数据', exact: true }).click();
  await page.locator('.va-error').waitFor();
  expect(await page.locator('.va-status').textContent()).toBe('真实记录');
  expect(await page.locator('.va-metrics').count()).toBe(0);
  await page.close(); expect(runtimeErrors).toEqual([]); checks.push('窄屏无溢出、模拟更新、失败不自动填充样例、无运行时错误');
}, 90_000);
