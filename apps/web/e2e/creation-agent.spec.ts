import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { expect, test } from "@playwright/test";
import { db } from "@content-center/db";
import { auth } from "../lib/auth";

test("creation controls, selected editing, locks, history restoration and responsive layout", async ({ page, context }) => {
  const userId = "creation-browser-" + randomUUID(); let workspaceId = "";
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const output = path.resolve("output/creation-agent-quality"); await mkdir(output, { recursive: true });
  try {
    await db.user.create({ data: { id: userId, name: "创作验收", email: userId + "@test.invalid" } });
    workspaceId = (await db.workspace.create({ data: { name: "创作浏览器隔离", slug: userId, members: { create: { userId, role: "OWNER" } } } })).id;
    const project = await db.contentProject.create({ data: { workspaceId, createdById: userId, title: "校长个人 IP 创作" } });
    const branch = await db.draftBranch.create({ data: { workspaceId, projectId: project.id, title: "校长口播", workingTitle: "校长口播", workingBody: "第一段保持原样。\n\n第二段需要自然表达。\n\n第三段保持原样。", version: 1, createdById: userId, updatedById: userId } });
    const revision = await db.draftRevision.create({ data: { workspaceId, projectId: project.id, draftBranchId: branch.id, revision: 1, title: "校长口播", body: branch.workingBody, outline: [], origin: "HUMAN", createdById: userId } });
    await db.draftBranch.update({ where: { id: branch.id }, data: { currentRevisionId: revision.id } });
    const artifact = await db.artifact.create({ data: { workspaceId, projectId: project.id, draftBranchId: branch.id, title: "校长口播", createdById: userId } });
    const session = await db.session.create({ data: { userId, token: randomUUID() + randomUUID(), activeWorkspaceId: workspaceId, expiresAt: new Date(Date.now() + 3600000) } });
    const require = createRequire(path.resolve("apps/web/package.json"));
    const cookies = require(require.resolve("better-call", { paths: [path.dirname(require.resolve("better-auth/cookies"))] }));
    const signed = await cookies.serializeSignedCookie("teardown-test.session_token", session.token, (await auth.$context).secret, { path: "/", httpOnly: true, sameSite: "lax" }) as string;
    const pair = signed.split(";")[0]!, separator = pair.indexOf("=");
    await context.addCookies([{ name: pair.slice(0, separator), value: pair.slice(separator + 1), url: "http://localhost:3016" }]);
    await page.goto(`/dashboard?project=${project.id}`);
    await expect(page.getByLabel("任务类型", { exact: true })).toBeEnabled({ timeout: 30000 });
    await page.getByLabel("任务类型", { exact: true }).selectOption("SCRIPT");
    await page.getByLabel("创作模式", { exact: true }).selectOption("EXPLORE");
    await page.getByLabel("回答深度", { exact: true }).selectOption("DEEP");
    await page.getByText("表达与身份", { exact: true }).click();
    await page.getByLabel("表达方式", { exact: true }).selectOption("SPOKEN");
    await page.getByLabel("发散程度", { exact: true }).selectOption("WIDE");
    await page.getByLabel("账号或人物身份", { exact: true }).fill("面向家长的校长");
    await page.getByLabel("我的表达偏好", { exact: true }).fill("自然直接，不用口号");
    await page.getByRole("button", { name: "保存身份与偏好", exact: true }).click();
    await expect(page.getByText("已保存我的身份与表达偏好；其他档案内容保留。", { exact: true })).toBeVisible();
    expect((await db.creatorProfile.findUniqueOrThrow({ where: { workspaceId_userId: { workspaceId, userId } } })).preferredStyle).toBe("自然直接，不用口号");
    await page.screenshot({ path: path.join(output, "creation-controls-desktop.png") });
    await page.getByText("表达与身份", { exact: true }).click();
    const requestPromise = page.waitForRequest(request => request.url().endsWith(`/api/projects/${project.id}/assistant`) && request.method() === "POST");
    await page.getByLabel("和鑫小助说", { exact: true }).fill("写一个校长口播稿");
    await page.getByRole("button", { name: "发送给鑫小助", exact: true }).click();
    expect((await requestPromise).postDataJSON().creationOptions).toMatchObject({ task: "SCRIPT", mode: "EXPLORE", depth: "DEEP", naturalness: "SPOKEN", divergence: "WIDE", persona: "面向家长的校长" });
    await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0, { timeout: 30000 });
    const run = await db.aIRun.findFirstOrThrow({ where: { projectId: project.id, action: "PROJECT_ASSISTANT" }, orderBy: { createdAt: "desc" } });
    expect(run.provider).toBe("MOCK");
    expect(JSON.stringify(run.metadata)).toContain("EXPLORE");
    await page.reload();
    await expect(page.getByLabel("创作模式", { exact: true })).toHaveValue("EXPLORE", { timeout: 30000 });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, "creation-controls-mobile.png") });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`/dashboard?project=${project.id}&node=artifact:${artifact.id}`);
    const editor = page.getByRole("region", { name: "项目成果", exact: true });
    await expect(editor.getByLabel("成果正文", { exact: true })).toHaveValue(branch.workingBody, { timeout: 30000 });
    await editor.getByRole("button", { name: "确认并锁定成果", exact: true }).click();
    await expect(editor.getByRole("button", { name: "解锁成果", exact: true })).toBeEnabled();
    await expect(editor.getByLabel("成果正文", { exact: true })).toBeDisabled();
    const lockedBranch = await db.draftBranch.findUniqueOrThrow({ where: { id: branch.id } });
    const rejected = await context.request.put(`/api/projects/${project.id}/artifacts/${artifact.id}`, { data: { expectedVersion: lockedBranch.version, title: artifact.title, body: "不能绕过锁定" } });
    expect(rejected.status()).toBe(403);
    await editor.getByRole("button", { name: "解锁成果", exact: true }).click();
    await expect(editor.getByLabel("成果正文", { exact: true })).toBeEnabled();
    await editor.getByLabel("成果正文", { exact: true }).fill("手动保存的新内容。");
    await editor.getByRole("button", { name: "保存修改", exact: true }).click();
    await expect(editor.getByText("成果已保存，旧版本保留。", { exact: true })).toBeVisible();
    await editor.getByRole("button", { name: "查看版本历史", exact: true }).click();
    const history = editor.getByRole("region", { name: "成果版本历史", exact: true });
    await history.locator("summary").last().click();
    await history.getByRole("button", { name: "恢复此版本", exact: true }).last().click();
    await expect(editor.getByLabel("成果正文", { exact: true })).toHaveValue(branch.workingBody);
    await editor.getByLabel("成果正文", { exact: true }).evaluate((element: HTMLTextAreaElement) => { element.focus(); const start = element.value.indexOf("第二段"); element.setSelectionRange(start, start); });
    await editor.getByLabel("成果正文", { exact: true }).press("Shift+End");
    await expect(editor.getByRole("button", { name: "通过 AI 修改选中内容", exact: true })).toBeVisible();
    await editor.getByRole("button", { name: "通过 AI 修改选中内容", exact: true }).click();
    await expect(editor).toBeVisible();
    await expect(page.getByLabel("和鑫小助说", { exact: true })).toBeFocused();
    await expect(page.getByText(/只修改选中的 \d+ 个字，其他内容保留/)).toBeVisible();
    const localRequest = page.waitForRequest(request => request.url().endsWith(`/api/projects/${project.id}/assistant`) && request.method() === "POST");
    await page.getByLabel("和鑫小助说", { exact: true }).fill("更自然一点");
    await page.getByRole("button", { name: "发送给鑫小助", exact: true }).click();
    expect((await localRequest).postDataJSON().editScope).toMatchObject({ start: branch.workingBody.indexOf("第二段"), end: branch.workingBody.indexOf("\n\n第三段") });
    await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0, { timeout: 30000 });
    const reply = await db.assistantMessage.findFirstOrThrow({ where: { artifactId: artifact.id, role: "ASSISTANT", status: "COMPLETED" }, orderBy: { createdAt: "desc" } });
    expect(reply.content.startsWith("第一段保持原样。\n\n")).toBe(true); expect(reply.content.endsWith("\n\n第三段保持原样。")).toBe(true);
    await page.screenshot({ path: path.join(output, "creation-local-edit.png") });
    expect(errors).toEqual([]);
  } finally { if (workspaceId) await db.workspace.delete({ where: { id: workspaceId } }); await db.user.deleteMany({ where: { id: userId } }); await db.$disconnect(); }
});
