import { randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { chromium } from "@playwright/test";
import { expect, it, vi } from "vitest";
vi.mock("server-only", () => ({}));
import { db } from "@content-center/db";
import { auth } from "../lib/auth";
import { createTextArtifact, getArtifactForUser } from "../server/artifacts/service";
it.skipIf(!process.env.V4_BROWSER_ORIGIN)("keeps Conversation and Artifact visible, protects dirty edits and retains topic review deep links", async () => {
  const origin = process.env.V4_BROWSER_ORIGIN!, suffix = randomUUID(), email = `v4-browser-${suffix}@test.invalid`, password = `fixture-${suffix}`;
  let userId = "", workspaceId = ""; const browser = await chromium.launch({ channel: "msedge", headless: true });
  try {
    userId = (await auth.api.signUpEmail({ body: { name: "V4 浏览器夹具", email, password } })).user.id;
    workspaceId = (await db.workspace.create({ data: { name: "V4 浏览器隔离", slug: suffix, members: { create: { userId, role: "OWNER" } } } })).id;
    const projectId = (await db.contentProject.create({ data: { workspaceId, createdById: userId, title: "V4 项目持续创作" } })).id;
    const thread = await db.assistantThread.create({ data: { workspaceId, projectId, createdById: userId } });
    const message = await db.assistantMessage.create({ data: { threadId: thread.id, role: "ASSISTANT", status: "COMPLETED", content: "已保存的浏览器正文。" } });
    const artifact = await createTextArtifact({ workspaceId, projectId, userId, title: "真实成果夹具", sourceMessageId: message.id });
    const signed = await auth.api.signInEmail({ body: { email, password }, asResponse: true });
    const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
    await context.addCookies(signed.headers.getSetCookie().map(value => { const pair = value.split(";")[0]!, index = pair.indexOf("="); return { name: pair.slice(0, index), value: pair.slice(index + 1), url: origin }; }));
    const page = await context.newPage(); page.setDefaultTimeout(30000);
    await page.goto(`${origin}/dashboard?project=${projectId}&node=artifact:${artifact.artifactId}`, { waitUntil: "domcontentloaded", timeout: 90000 });
    await page.getByLabel("成果正文", { exact: true }).waitFor();
    expect(await page.getByRole("region", { name: "项目持续对话", exact: true }).isVisible()).toBe(true);
    expect(await page.locator(".artifact-window.is-embedded").isVisible()).toBe(true);
    expect(await page.getByRole("navigation", { name: "主导航", exact: true }).getByRole("link").count()).toBe(5);
    await mkdir("output/v4-s4/browser", { recursive: true });
    await page.screenshot({ path: "output/v4-s4/browser/project-desktop.png", fullPage: true });
    const body = page.getByLabel("成果正文", { exact: true }); await body.fill("浏览器修改后正文。");
    await page.getByRole("button", { name: "高级视图：Canvas 与平台稿", exact: true }).focus();
    await page.keyboard.press("Enter");
    const unsaved = page.getByRole("dialog", { name: "处理未保存内容", exact: true }); await unsaved.waitFor();
    await unsaved.getByRole("button", { name: "取消，保留编辑", exact: true }).click();
    expect(await body.inputValue()).toBe("浏览器修改后正文。");
    const savedResponse = page.waitForResponse(response => response.url().endsWith(`/artifacts/${artifact.artifactId}`) && response.request().method() === "PUT");
    await page.getByRole("button", { name: "保存修改", exact: true }).click();
    expect((await savedResponse).status()).toBe(200);
    await expect.poll(async () => (await getArtifactForUser({ workspaceId, projectId, userId, artifactId: artifact.artifactId })).content, { timeout: 30000 }).toBe("浏览器修改后正文。");
    await page.reload(); await body.waitFor(); expect(await body.inputValue()).toBe("浏览器修改后正文。");
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: "output/v4-s4/browser/project-mobile.png", fullPage: true });
    await page.goto(origin + "/home", { waitUntil: "domcontentloaded", timeout: 90000 });
    await page.getByRole("heading", { name: "鑫世界工作台", exact: true }).waitFor();
    expect(await page.getByRole("heading", { name: "最近的项目", exact: true }).isVisible()).toBe(true);
    await page.screenshot({ path: "output/v4-s4/browser/home-mobile.png", fullPage: true });
    await page.goto(origin + "/content-review", { waitUntil: "domcontentloaded", timeout: 90000 });
    expect(page.url()).toContain("/topics?view=review"); await page.getByRole("heading", { name: "选题审批", exact: true }).waitFor();
    await writeFile("output/v4-s4/browser/evidence.json", JSON.stringify({ projectId, artifactId: artifact.artifactId, realArtifactAPI: true, paidCalls: 0, desktop: 1600, mobile: 390, dirtyGuard: true, reopenedSave: true, legacyReviewRedirect: true }, null, 2));
    await context.close();
  } finally { await browser.close(); if (workspaceId) await db.workspace.delete({ where: { id: workspaceId } }); if (userId) await db.user.delete({ where: { id: userId } }); await db.$disconnect(); }
}, 180000);
